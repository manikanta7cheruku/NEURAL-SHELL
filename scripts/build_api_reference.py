"""
scripts/build_api_reference.py

Writes docs/reference/http-api.md from the FastAPI route decorators in
backend/. The reference is generated, not hand-written, so it always matches
the code. Run it after adding or changing an endpoint:

    python scripts/build_api_reference.py

It reads the source with ast (nothing is imported or started).
"""
import ast
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "reference", "http-api.md")
METHODS = {"get", "post", "put", "patch", "delete", "websocket"}


def _routes(path):
    with open(path, encoding="utf-8") as f:
        tree = ast.parse(f.read())
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        for dec in node.decorator_list:
            if not (isinstance(dec, ast.Call) and isinstance(dec.func, ast.Attribute)
                    and dec.func.attr in METHODS and dec.args and isinstance(dec.args[0], ast.Constant)):
                continue
            summary = next((k.value.value for k in dec.keywords
                            if k.arg == "summary" and isinstance(k.value, ast.Constant)), "")
            doc = (ast.get_docstring(node) or "").strip().splitlines()
            text = (summary or (doc[0] if doc else "")).replace(" — ", ": ").replace("—", ", ")
            yield dec.func.attr.upper(), dec.args[0].value, text.replace("|", "/")


def main():
    groups = {}
    backend = os.path.join(ROOT, "backend")
    for dirpath, _dirs, files in os.walk(backend):
        for name in sorted(files):
            if name.endswith(".py"):
                full = os.path.join(dirpath, name)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                for method, route, text in _routes(full):
                    groups.setdefault(rel, []).append((route, method, text))

    total = sum(len(v) for v in groups.values())
    lines = [
        "# HTTP API reference",
        "",
        "Generated by `scripts/build_api_reference.py` from the route decorators in `backend/`. Do not edit by hand.",
        "",
        "The backend listens on `http://127.0.0.1:7777` only (never on the network). The desktop app, the task panel,",
        "the overlay and the Chrome extension are its only clients. There is no authentication because nothing outside",
        "this computer can reach it.",
        "",
        f"{total} endpoints in {len(groups)} files.",
        "",
    ]
    for rel in sorted(groups):
        lines += [f"## `{rel}`", "", "| Method | Path | What it does |", "|---|---|---|"]
        for route, method, text in sorted(groups[rel]):
            lines.append(f"| {method} | `{route}` | {text or '_Not documented yet_'} |")
        lines.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"API reference written: {total} endpoints -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
